async def main() -> None:
    # Пробуем загрузить с диска, иначе из Google
    if not sheets_cache.load_from_disk():
        print("Дискового кэша нет — загружаю из Google Sheets...")
        await sheets_cache.load_all()

    # Строим словарь: tema_kod -> количество вопросов
    counts: dict[str, int] = {}
    for row in sheets_cache.topic_tests_rows:
        kod = (row.get("Тема_код") or "").strip()
        if kod:
            counts[kod] = counts.get(kod, 0) + 1

    print(f"\nВсего вопросов по темам: {sum(counts.values())}")
    print(f"Уникальных кодов тем в таблице: {len(counts)}\n")

    missing: list[str] = []
    ok: list[str] = []

    for sec_num, subtopics in SUBTOPICS.items():
        codes = SUBTOPIC_CODES.get(sec_num, [])
        seen_codes: set[str] = set()  # не дублируем объединённые темы

        for i, name in enumerate(subtopics):
            kod = codes[i] if i < len(codes) else f"{sec_num}_?"
            if kod in seen_codes:
                continue
            seen_codes.add(kod)

            n = counts.get(kod, 0)
            label = f"  {kod:10s} | {n:4d} вопр. | {name[:55]}"
            if n == 0:
                missing.append(label)
            else:
                ok.append(label)

    if missing:
        print("❌ ТЕМЫ БЕЗ ТЕСТОВ:")
        for line in missing:
            print(line)
    else:
        print("✅ Все темы имеют тесты!")

    print(f"\n✅ ТЕМ С ТЕСТАМИ: {len(ok)}")
    for line in ok:
        print(line)

    # Коды в таблице, которые не совпадают ни с одним кодом из бота
    known_codes = {
        kod
        for codes in SUBTOPIC_CODES.values()
        for kod in codes
    }
    unknown = sorted(k for k in counts if k not in known_codes)
    if unknown:
        print(f"\n⚠️  КОДЫ В ТАБЛИЦЕ, КОТОРЫХ НЕТ В БОТЕ ({len(unknown)}):")
        for k in unknown:
            print(f"  {k:10s} | {counts[k]} вопр.")


asyncio.run(main())
